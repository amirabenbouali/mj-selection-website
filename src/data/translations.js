function localizedWineCards(language) {
  return wineCatalog.map((wine) => {
    const card = toWineCard(wine)
    const country = countryTranslations[language][wine.country] || wine.country
    const style = styleTranslations[language][wine.style] || wine.style

    return {
      ...card,
      region: `${wine.region}, ${country}`,
      style,
    }
  })
}

