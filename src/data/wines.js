function getWineCategories(style) {
  const categories = []

  if (style.includes('Red')) {
    categories.push('red')
  }

  if (style.includes('White') || style === 'Orange') {
    categories.push('white')
  }

  if (style.includes('Rosé')) {
    categories.push('rose')
  }

  if (style.includes('Champagne') || style.includes('Sparkling') || style.includes('Pet Nat')) {
    categories.push('sparkling')
  }

  return categories
}

export function toWineCard(wine) {
  const priceSeed = [...wine.id].reduce((sum, char) => sum + char.charCodeAt(0), 0)
  const price = 24 + (priceSeed % 18) * 2
  const stock = 3 + (priceSeed % 15)

  return {
    id: wine.id,
    name: wine.name,
    producer: wine.producer,
    region: `${wine.region}, ${wine.country}`,
    regionName: wine.region,
    style: wine.style,
    grapes: wine.grapes,
    notes: wine.notes,
    denomination: wine.denomination,
    price,
    stock,
    available: stock > 0,
    categories: getWineCategories(wine.style),
  }
}
